@app.post("/setup")
async def setup_post(
    request: Request,
    lab_name: str = Form(...),
    lab_code: str = Form(...),
    lab_type: str = Form("General"),
    lab_type_other: str = Form(""),
    husbandry_label: str = Form("Organisms"),
    husbandry_custom: str = Form(""),
    primary_color: str = Form("#2563eb"),
    accent_color: str = Form("#0d9488"),
    timezone: str = Form("America/Los_Angeles"),
    logo_path: str = Form(""),
    admin_user: str = Form(...),
    admin_pw: str = Form(...),
    admin_pw2: str = Form(...),
):
    if db.has_lab_config():
        return redirect("/login")
    form = await request.form()
    selected = form.getlist("modules")
    mods = {k: (k in selected) for k in DEFAULT_MODULES}

    errors = []
    if not lab_name.strip():
        errors.append("Lab name is required.")
    if not lab_code.strip():
        errors.append("Lab code is required.")
    if not admin_user.strip():
        errors.append("Admin username is required.")
    if not admin_pw or len(admin_pw) < 6:
        errors.append("Admin password must be at least 6 characters.")
    if admin_pw != admin_pw2:
        errors.append("Passwords do not match.")
    if errors:
        for e in errors:
            flash(request, e, "error")
        return redirect("/setup")

    final_type = lab_type_other.strip() or lab_type
    final_h = husbandry_custom.strip() or husbandry_label
    try:
        code = validate_lab_code(lab_code)
    except ValueError as e:
        flash(request, str(e), "error")
        return redirect("/setup")

    db.save_lab_config(
        lab_name=lab_name.strip(),
        lab_code=code,
        primary_color=primary_color,
        accent_color=accent_color,
        timezone=timezone.strip() or "UTC",
        logo_path=logo_path.strip() or None,
        modules=mods,
        lab_type=final_type,
        husbandry_label=final_h,
    )
    if not db.get_user_by_username(admin_user.strip()):
        db.create_user(
            admin_user.strip(),
            hash_password(admin_pw),
            "admin",
            admin_user.strip(),
        )
    db.audit(
        "lab_setup",
        username=admin_user.strip(),
        role="admin",
        details=f"lab={lab_name.strip()} type={final_type}",
    )
    # Move/register into data/labs/<CODE>/lab.db
    register_lab(code, lab_name.strip(), make_active=True)
    reset_db_cache()
    flash(request, "Lab configured. Please sign in.", "success")
    return redirect("/login")


