def safe_upload_path(directory: Path, filename: str) -> Path:
    """Resolve a filename under directory; reject path traversal."""
    directory = directory.resolve()
    raw = Path(filename or "").name
    if not raw or raw in (".", ".."):
        raise ValueError("Invalid filename")
    # Strip weird characters that confuse filesystems / Content-Disposition
    safe = "".join(c if c.isalnum() or c in "._-+" else "_" for c in raw)
    if not safe or safe.startswith("."):
        raise ValueError("Invalid filename")
    dest = (directory / safe).resolve()
    if not str(dest).startswith(str(directory) + "/") and dest != directory:
        # Windows-friendly: also allow same root via relative_to
        try:
            dest.relative_to(directory)
        except ValueError as e:
            raise ValueError("Path escapes upload directory") from e
    return dest


def safe_structure_read(rel_or_abs: str) -> Path:
    """Only allow reading structure files under uploads/structures."""
    path = Path(rel_or_abs)
    if not path.is_absolute():
        path = (ROOT / path).resolve()
    else:
        path = path.resolve()
    base = STRUCTURES_DIR.resolve()
    try:
        path.relative_to(base)
    except ValueError as e:
        raise ValueError("Structure path outside uploads/structures") from e
    return path

