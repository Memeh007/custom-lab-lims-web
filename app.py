def ctx(request: Request, active: str = "", **extra: Any) -> dict:
    config = db.get_lab_config()
    user = current_user(request)
    # Session lab binding — force re-login if active lab changed underfoot
    if user:
        sess_lab = request.session.get("lab_code")
        cur = active_lab_code()
        if cur and sess_lab and sess_lab != cur:
            request.session.clear()
            user = None
    base = {
        "request": request,
        "config": config,
        "user": user,
        "nav": build_nav(config) if config and user else [],
        "active": active,
        "flashes": pop_flashes(request),
        "can_write": role_can(user["role"], "write") if user else False,
        "can_admin": role_can(user["role"], "admin") if user else False,
        "active_lab_code": active_lab_code(),
        "labs_registry": list_labs(),
    }
    base.update(extra)
    return base


