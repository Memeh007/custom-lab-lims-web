@app.post("/login")
async def login_post(
    request: Request,
    username: str = Form(...),
    password: str = Form(...),
):
    if not db.has_lab_config():
        return redirect("/setup")
    row = db.get_user_by_username(username.strip())
    if row and verify_password(row["password_hash"], password):
        request.session["user"] = {
            "id": row["id"],
            "username": row["username"],
            "role": row["role"],
            "display_name": row.get("display_name") or row["username"],
        }
        request.session["lab_code"] = active_lab_code()
        db.audit("login", row["username"], row["role"], "success")
        return redirect("/")
    db.audit("login_failed", username.strip() or None, None, "bad credentials")
    flash(request, "Invalid username or password.", "error")
    return redirect("/login")


